_TRANSLATION_CONTEXTS = (
    i18n_contexts.default,
    i18n_contexts.operator_default,
    i18n_contexts.id_windowmanager,
)


def _build_contextual_translations(base_mapping):
    contextual_mapping = {}
    for source_key, translated_text in base_mapping.items():
        if isinstance(source_key, tuple):
            _, source_text = source_key
        else:
            source_text = source_key
        for context_name in _TRANSLATION_CONTEXTS:
            contextual_mapping[(context_name, source_text)] = translated_text
    return contextual_mapping


_TRANSLATIONS_ZH_TO_EN = _build_contextual_translations(_TRANSLATIONS_ZH_TO_EN_BASE)


translations_dict = {
    "en_US": _TRANSLATIONS_ZH_TO_EN,
    "en_GB": _TRANSLATIONS_ZH_TO_EN,
}


def register():
    try:
        bpy.app.translations.unregister(__name__)
    except (ValueError, RuntimeError):
        pass
    bpy.app.translations.register(__name__, translations_dict)


def unregister():
    try:
        bpy.app.translations.unregister(__name__)
    except (ValueError, RuntimeError):
        pass


